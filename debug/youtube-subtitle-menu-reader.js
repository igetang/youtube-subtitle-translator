/**
 * YouTube字幕菜单读取工具
 *
 * 功能：读取YouTube播放器设置-字幕菜单中的所有选项
 * 使用：复制到F12控制台运行
 */

(function() {
  console.clear();
  console.log('%c🔍 YouTube字幕菜单读取工具', 'font-size: 16px; color: #2196F3; font-weight: bold');
  console.log('='.repeat(50));

  // 方法1：通过Player API读取
  function readFromAPI() {
    console.log('\n%c📊 方法1: Player API 读取', 'color: #4CAF50; font-weight: bold');

    const player = document.getElementById('movie_player');
    if (!player) {
      console.error('❌ 找不到播放器');
      return;
    }

    // 加载字幕模块
    if (typeof player.loadModule === 'function') {
      player.loadModule("captions");
      player.loadModule("cc");
    }

    // 获取字幕轨道列表
    let tracks = [];
    try {
      // 尝试captions模块
      const captionTracks = player.getOption('captions', 'tracklist');
      if (captionTracks) {
        console.log('✅ 从captions模块获取到轨道');
        tracks = captionTracks;
      }
    } catch (e) {
      console.warn('captions模块获取失败:', e);
    }

    if (tracks.length === 0) {
      try {
        // 尝试cc模块
        const ccTracks = player.getOption('cc', 'tracklist');
        if (ccTracks) {
          console.log('✅ 从cc模块获取到轨道');
          tracks = ccTracks;
        }
      } catch (e) {
        console.warn('cc模块获取失败:', e);
      }
    }

    console.log(`📋 API读取到 ${tracks.length} 条字幕轨道:`);

    // 详细输出每条轨道
    tracks.forEach((track, index) => {
      const lang = track.languageCode || track.language_code || track.langCode;
      const name = track.name || track.displayName || track.label;
      const kind = track.kind || (track.is_asr ? 'asr' : 'manual');
      const vssId = track.vssId || track.vss_id;

      console.log(`  [${index + 1}] ${lang} - ${name}` +
                  (kind === 'asr' ? ' (自动生成)' : '') +
                  (vssId ? ` [vssId: ${vssId}]` : ''));
    });

    return tracks;
  }

  // 方法2：通过UI菜单读取
  function readFromUI() {
    console.log('\n%c📊 方法2: UI菜单读取', 'color: #9C27B0; font-weight: bold');

    // 先打开设置菜单
    const settingsBtn = document.querySelector('.ytp-settings-button');
    if (!settingsBtn) {
      console.error('❌ 找不到设置按钮');
      return;
    }

    // 点击设置按钮
    settingsBtn.click();

    setTimeout(() => {
      // 查找字幕菜单项
      const menuItems = document.querySelectorAll('.ytp-settings-menu .ytp-menuitem');
      let subtitleMenuItem = null;

      menuItems.forEach(item => {
        const label = item.querySelector('.ytp-menuitem-label');
        if (label && (label.textContent.includes('字幕') ||
                     label.textContent.includes('Subtitle') ||
                     label.textContent.includes('Caption'))) {
          subtitleMenuItem = item;
        }
      });

      if (!subtitleMenuItem) {
        console.error('❌ 未找到字幕菜单项');
        // 关闭菜单
        settingsBtn.click();
        return;
      }

      console.log('✅ 找到字幕菜单项');

      // 点击字幕菜单
      subtitleMenuItem.click();

      setTimeout(() => {
        // 读取字幕选项
        const subtitleOptions = document.querySelectorAll('.ytp-panel-menu .ytp-menuitem');
        console.log(`📋 UI菜单读取到 ${subtitleOptions.length} 个字幕选项:`);

        const options = [];
        subtitleOptions.forEach((option, index) => {
          const label = option.querySelector('.ytp-menuitem-label');
          const content = option.querySelector('.ytp-menuitem-content');

          if (label) {
            const text = label.textContent.trim();
            const isSelected = option.getAttribute('aria-checked') === 'true';
            const hasAutoGen = text.includes('自动生成') ||
                              text.includes('auto-generated') ||
                              text.includes('(auto)');

            options.push({
              index: index + 1,
              text: text,
              selected: isSelected,
              autoGenerated: hasAutoGen
            });

            console.log(`  [${index + 1}] ${text}` +
                       (isSelected ? ' ✓ [当前选中]' : '') +
                       (hasAutoGen ? ' 🤖' : ''));
          }
        });

        // 关闭菜单
        setTimeout(() => {
          // 点击返回或直接关闭
          const backBtn = document.querySelector('.ytp-panel-back-button');
          if (backBtn) {
            backBtn.click();
            setTimeout(() => settingsBtn.click(), 100);
          } else {
            settingsBtn.click();
          }
        }, 1000);

        return options;
      }, 300);
    }, 300);
  }

  // 方法3：通过Player Response读取
  function readFromPlayerResponse() {
    console.log('\n%c📊 方法3: PlayerResponse 读取', 'color: #FF5722; font-weight: bold');

    const player = document.getElementById('movie_player');
    if (!player || !player.getPlayerResponse) {
      console.error('❌ 无法获取PlayerResponse');
      return;
    }

    try {
      const response = player.getPlayerResponse();
      const captions = response?.captions;

      if (!captions) {
        console.log('❌ PlayerResponse中没有字幕信息');
        return;
      }

      // 读取字幕轨道
      const tracks = captions.playerCaptionsTracklistRenderer?.captionTracks || [];
      const translationLanguages = captions.playerCaptionsTracklistRenderer?.translationLanguages || [];

      console.log(`📋 PlayerResponse读取到 ${tracks.length} 条字幕轨道:`);

      tracks.forEach((track, index) => {
        const lang = track.languageCode;
        const name = track.name?.simpleText || track.name?.runs?.[0]?.text || '';
        const kind = track.kind;
        const vssId = track.vssId;
        const baseUrl = track.baseUrl;

        console.log(`  [${index + 1}] ${lang} - ${name}` +
                   (kind === 'asr' ? ' (自动生成)' : '') +
                   (vssId ? ` [vssId: ${vssId.substr(0, 8)}...]` : '') +
                   (baseUrl ? ' ✓URL' : ''));
      });

      if (translationLanguages.length > 0) {
        console.log(`\n📋 可翻译语言: ${translationLanguages.length} 种`);
      }

      return tracks;
    } catch (e) {
      console.error('❌ 读取PlayerResponse失败:', e);
    }
  }

  // 综合读取函数
  function readAll() {
    console.log('%c🚀 开始综合读取所有字幕信息...', 'color: #00BCD4; font-size: 14px; font-weight: bold');

    // 1. API读取
    const apiTracks = readFromAPI();

    // 2. PlayerResponse读取
    const prTracks = readFromPlayerResponse();

    // 3. UI读取（延迟执行避免干扰）
    setTimeout(() => {
      readFromUI();

      // 4. 对比分析
      setTimeout(() => {
        console.log('\n%c📊 对比分析:', 'color: #673AB7; font-weight: bold');
        console.log('API轨道数:', apiTracks?.length || 0);
        console.log('PlayerResponse轨道数:', prTracks?.length || 0);
        console.log('UI选项数: 请查看上方UI读取结果');

        // 查找差异
        if (apiTracks && prTracks) {
          const apiLangs = new Set(apiTracks.map(t => t.languageCode || t.language_code));
          const prLangs = new Set(prTracks.map(t => t.languageCode));

          const onlyInAPI = [...apiLangs].filter(l => !prLangs.has(l));
          const onlyInPR = [...prLangs].filter(l => !apiLangs.has(l));

          if (onlyInAPI.length > 0) {
            console.log('仅在API中:', onlyInAPI);
          }
          if (onlyInPR.length > 0) {
            console.log('仅在PlayerResponse中:', onlyInPR);
          }
        }
      }, 2000);
    }, 500);
  }

  // 快速测试函数
  window.ytSubtitleMenu = {
    readAPI: readFromAPI,
    readUI: readFromUI,
    readPlayerResponse: readFromPlayerResponse,
    readAll: readAll,

    // 快捷函数：只计数
    count: function() {
      console.log('\n%c📈 快速统计:', 'color: #FFC107; font-weight: bold');

      const player = document.getElementById('movie_player');
      if (player) {
        // API计数
        const tracks = player.getOption('captions', 'tracklist') ||
                      player.getOption('cc', 'tracklist') || [];
        console.log('API轨道数:', tracks.length);

        // 筛选不同类型
        const manual = tracks.filter(t => !t.kind || t.kind !== 'asr');
        const asr = tracks.filter(t => t.kind === 'asr');
        console.log('  - 手动字幕:', manual.length);
        console.log('  - 自动生成:', asr.length);

        // 语言统计
        const langs = new Set(tracks.map(t => t.languageCode || t.language_code));
        console.log('  - 语言种数:', langs.size);
        console.log('  - 语言列表:', [...langs].sort().join(', '));
      }
    }
  };

  // 提示信息
  console.log('='.repeat(50));
  console.log('%c📌 使用方法:', 'color: #673AB7; font-size: 14px; font-weight: bold');
  console.log('  ytSubtitleMenu.readAPI() - 从Player API读取');
  console.log('  ytSubtitleMenu.readUI() - 从UI菜单读取');
  console.log('  ytSubtitleMenu.readPlayerResponse() - 从PlayerResponse读取');
  console.log('  ytSubtitleMenu.readAll() - 综合读取所有信息');
  console.log('  ytSubtitleMenu.count() - 快速统计');
  console.log('='.repeat(50));

  // 自动执行快速统计
  ytSubtitleMenu.count();

  console.log('\n💡 提示: 运行 ytSubtitleMenu.readAll() 查看完整信息');

})();