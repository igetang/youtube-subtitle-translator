/**
 * UI事件的结构化类型定义
 * 用于MessageBus中传递的UI相关事件
 */
export interface UIActionEvent {
  /**
   * UI事件的具体类型
   */
  type: 'button_click' | 'tooltip_show' | 'state_change';
  
  /**
   * 事件携带的数据
   */
  payload: {
    /**
     * 按钮类型，在 button_click 事件中使用
     */
    buttonType?: 'translate' | 'settings';
    
    /**
     * tooltip文本，在 tooltip_show 事件中使用
     */
    tooltipText?: string;

    /**
     * 新的状态值
     */
    newState?: any;
    
    /**
     * 触发事件的源头
     */
    source?: string;
  };
}

/**
 * 消息类型枚举
 */
export enum MessageType {
  // 系统控制消息
  EXTENSION_INIT = 'extension_init',
  EXTENSION_SHUTDOWN = 'extension_shutdown',
  
  // 字幕相关消息
  SUBTITLE_DETECTED = 'subtitle_detected',
  SUBTITLE_UPDATED = 'subtitle_updated',
  SUBTITLE_REQUEST = 'subtitle_request',
  
  // 翻译相关消息
  TRANSLATION_REQUEST = 'translation_request',
  TRANSLATION_RESPONSE = 'translation_response',
  TRANSLATION_ERROR = 'translation_error',
  TRANSLATION_TOGGLE = 'translation_toggle',
  
  // UI状态消息
  UI_STATE_UPDATE = 'ui_state_update',
  BUTTON_STATE_CHANGE = 'button_state_change',
  
  // 设置相关消息
  SETTINGS_GET = 'settings_get',
  SETTINGS_UPDATE = 'settings_update',
  SETTINGS_RESET = 'settings_reset',
  
  // SidePanel消息
  SIDEPANEL_OPEN = 'sidepanel_open',
  SIDEPANEL_CLOSE = 'sidepanel_close',
  SIDEPANEL_DATA_REQUEST = 'sidepanel_data_request',
  SIDEPANEL_DATA_RESPONSE = 'sidepanel_data_response',
  
  // 缓存管理消息
  CACHE_GET = 'cache_get',
  CACHE_SET = 'cache_set',
  CACHE_CLEAR = 'cache_clear',
  
  // 错误处理消息
  ERROR_REPORT = 'error_report',
  SHOW_ERROR_MESSAGE = 'show_error_message',
  CLEAR_ERROR_MESSAGE = 'clear_error_message',
  
  // 性能监控消息
  PERFORMANCE_STATS = 'performance_stats'
}

/**
 * 消息发送者类型
 */
export enum MessageSender {
  CONTENT_SCRIPT = 'content_script',
  MAIN_WORLD_SCRIPT = 'main_world_script',
  BACKGROUND_SCRIPT = 'background_script',
  SIDEPANEL = 'sidepanel',
  POPUP = 'popup'
}

/**
 * 消息优先级
 */
export enum MessagePriority {
  LOW = 'low',
  NORMAL = 'normal',
  HIGH = 'high',
  URGENT = 'urgent'
}

/**
 * 基础消息接口
 */
export interface BaseMessage {
  /** 消息类型 */
  type: MessageType;
  /** 消息ID (用于追踪和响应) */
  messageId: string;
  /** 发送者 */
  sender: MessageSender;
  /** 接收者 (可选，用于定向发送) */
  receiver?: MessageSender;
  /** 时间戳 */
  timestamp: Timestamp;
  /** 消息优先级 */
  priority: MessagePriority;
  /** 标签页ID (可选) */
  tabId?: number;
  /** 响应超时时间 (毫秒) */
  timeout?: number;
}

/**
 * 响应消息接口
 */
export interface ResponseMessage<T = any> extends BaseMessage {
  /** 原始消息ID */
  originalMessageId: string;
  /** 是否成功 */
  success: boolean;
  /** 响应数据 */
  data?: T;
  /** 错误信息 */
  error?: string;
}

