/**
 * 所有消息类型的联合
 */
export type ExtensionMessage = 
  | SubtitleDetectedMessage
  | SubtitleUpdatedMessage
  | SubtitleRequestMessage
  | TranslationRequestMessage
  | TranslationResponseMessage
  | TranslationErrorMessage
  | TranslationToggleMessage
  | UIStateUpdateMessage
  | ButtonStateChangeMessage
  | SettingsGetMessage
  | SettingsUpdateMessage
  | SettingsResetMessage
  | SidePanelOpenMessage
  | SidePanelCloseMessage
  | SidePanelDataRequestMessage
  | SidePanelDataResponseMessage
  | CacheGetMessage
  | CacheSetMessage
  | CacheClearMessage
  | ErrorReportMessage
  | ShowErrorMessage
  | ClearErrorMessage
  | PerformanceStatsMessage;

/**
 * 消息处理器类型
 */
export type MessageHandler<T extends ExtensionMessage = ExtensionMessage> = (
  message: T,
  sender: chrome.runtime.MessageSender,
  sendResponse: (response?: any) => void
) => boolean | void | Promise<any>;

/**
 * 消息路由配置
 */
export interface MessageRoute {
  /** 消息类型 */
  type: MessageType;
  /** 处理器 */
  handler: MessageHandler;
  /** 是否需要响应 */
  requiresResponse?: boolean;
  /** 超时时间 (毫秒) */
  timeout?: number;
  /** 是否允许跨标签页 */
  allowCrossTab?: boolean;
}

/**
 * 消息验证规则
 */
export interface MessageValidationRule {
  /** 消息类型 */
  type: MessageType;
  /** 必需字段 */
  requiredFields: string[];
  /** 可选字段 */
  optionalFields?: string[];
  /** 自定义验证函数 */
  customValidator?: (message: ExtensionMessage) => boolean;
}

