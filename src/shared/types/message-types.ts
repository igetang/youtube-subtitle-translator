export interface MessageSendResult<T = any> {
  /** 是否成功 */
  success: boolean;
  /** 响应数据 */
  response?: T;
  /** 错误信息 */
  error?: string;
  /** 发送时间戳 */
  sentAt: Timestamp;
  /** 响应时间戳 */
  respondedAt?: Timestamp;
  /** 往返时间 (毫秒) */
  roundTripTime?: number;
}

