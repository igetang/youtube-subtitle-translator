/**
 * 字幕类型定义 - 统一字幕轨道相关接口
 * 
 * 📝 设计说明：
 * - CaptionTrack: YouTube API原始格式，包含完整字幕轨道信息
 * - SimplifiedCaptionTrack: 简化格式，用于内存缓存和存储
 * - 提供双向转换函数，确保类型安全和向后兼容
 * 
 * @author Assistant
 * @date 2024-12-26
 */

import { LanguageCode } from './core-types';
import type { CaptionTrack } from './youtube-types';

// === 简化字幕轨道格式（用于缓存和存储）===

/**
 * 简化字幕轨道接口 - 用于内存缓存和本地存储
 * 提取核心信息，减少存储开销
 */
export interface SimplifiedCaptionTrack {
  /** 字幕文件URL */
  baseUrl: string;
  /** 语言代码 */
  languageCode: string;
  /** 显示名称（如：德语, 法语, English）- 从CaptionTrack.name.simpleText提取 */
  name: string;
  /** 轨道类型（可选）*/
  kind?: 'asr' | 'forced' | undefined;
}

// === 处理过的字幕轨道（用于UI显示）===

/**
 * 处理过的字幕轨道接口 - 用于UI组件显示
 * 包含格式化后的信息，便于前端展示
 */
export interface ProcessedCaptionTrack {
  /** 语言代码 */
  languageCode: LanguageCode;
  /** 显示名称 */
  displayName: string;
  /** 原生名称（如果有）*/
  nativeName?: string;
  /** 是否为自动生成字幕 */
  isAutoGenerated: boolean;
  /** 是否可用于翻译 */
  isTranslatable: boolean;
  /** 原始轨道数据引用 */
  originalTrack: SimplifiedCaptionTrack;
}

// === 字幕轨道查询结果 ===

